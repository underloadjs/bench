// core/types.ts — shared data shapes for the @agentic/bench engine.
//
// The engine is intentionally provider-agnostic: it measures ANY model behind
// a minimal `BenchProvider` interface (a single streaming `generate` call).
// Wrapping an existing client (e.g. `ChatCompletion` from @agentic/cloud) is a
// one-line adapter:
//
//   const provider: BenchProvider = {
//       model: chat.model,
//       generate: (prompt, onUpdate) => chat.stream(prompt, onUpdate)
//   };
//
// Time units: all durations are SECONDS (timings) unless noted; the clock hook
// reports MILLISECONDS so callers can pass performance.now-like sources.

// Per-request token usage as reported by the provider (all optional — the
// engine estimates from content length when usage is missing, mirroring the
// heuristic in packages/test/models/src/benchmark-model.ts:159).
export type BenchUsage = {
    // Tokens consumed by the prompt
    promptTokens?: number;
    // Tokens consumed by the generated content
    completionTokens?: number;
    // Combined total (defaults to prompt + completion when omitted)
    totalTokens?: number;
};

// The result of a single model generation. `content` is the full response text.
// Extra fields pass through untouched so adapters can attach provider metadata.
export type BenchGeneration = {
    // Full text content generated by the model (the final answer — reasoning
    // models' chain-of-thought is NOT part of this; see `reasoning`)
    content: string;
    // Chain-of-thought text streamed by REASONING models BEFORE (or around)
    // the final answer. The wire format varies: deepseek/GLM-style
    // `delta.reasoning_content`, OpenRouter-style `delta.reasoning`. Those
    // tokens ARE output tokens — they count toward completion accounting and
    // the decode phase. Absent for plain (non-reasoning) models/streams.
    reasoning?: string;
    // Model identifier as reported by the provider (informational)
    model?: string;
    // Optional token usage accounting
    usage?: BenchUsage;
    // Allow arbitrary provider-specific fields
    [key: string]: unknown;
};

// One chat message in a multi-turn conversation. The growing-context
// scenario replays FULL histories on every turn — strict continuation is
// what makes each request a pure suffix append of the previous
// prompt+response (the only shape per-lane retained-KV engines can reuse).
export type BenchMessage = {
    role: 'user' | 'assistant' | 'system';
    content: string;
};

// Minimal model adapter the benchmark engine runs against.
// Implementations wrap any chat client (OpenAI-compatible, Anthropic, local).
export type BenchProvider = {
    // Stable identifier for the model (used as the report's `model` key)
    model: string;
    // Optional friendly display label shown in the dashboard UI
    label?: string;
    // Generates a completion for `prompt`. `onUpdate` is invoked per streamed
    // chunk (may be omitted for non-streaming providers; in that case the
    // engine records TTFT = 0 for the run). `signal` is the run's cancellation
    // signal — streaming transports forward it to fetch so an aborted run
    // rejects immediately instead of streaming to completion; adapters may
    // ignore it (the engine still records the run as cancelled).
    generate: (prompt: string, onUpdate?: (chunk: string) => void, signal?: AbortSignal) => Promise<BenchGeneration>;
    // Optional multi-turn generation: streams a FULL conversation (messages
    // array) instead of a single user prompt. Used by the growing-context
    // scenario — agentic continuation requires resending the accumulated
    // history every turn. Omitted = single-prompt-only provider; the
    // conversation scenario reports the model as unsupported and settles.
    generateConversation?: (
        messages: BenchMessage[],
        onUpdate?: (chunk: string) => void,
        signal?: AbortSignal
    ) => Promise<BenchGeneration>;
};

// One measured iteration of the benchmark.
// All time fields are relative to the moment the RUN started (not the whole
// bench) unless noted; `startTime` is relative to the bench start and is used
// by the UI to order/annotate runs when concurrency > 1.
export type BenchRun = {
    // 0-based iteration index (matches config.iterations ordering)
    index: number;
    // Seconds after bench start when this run began
    startTime: number;
    // Time to first token, in seconds (0 when the provider never streamed a
    // chunk or the run failed before any chunk)
    ttft: number;
    // Wall time for the full generation, in seconds
    totalTime: number;
    // Prompt tokens (provider usage, or ~content/4 estimate)
    promptTokens: number;
    // Completion tokens (provider usage, or ~content/4 estimate)
    completionTokens: number;
    // Total tokens (defaults to prompt + completion)
    totalTokens: number;
    // Character length of the generated content (0 for failed runs)
    contentLength: number;
    // PREFILL speed (the INPUT metric): promptTokens / ttft — how many
    // context tokens per second the engine chewed through before the first
    // output token. 0 when the run never streamed (ttft 0) or failed. This
    // is the meaningful rate for prefill-dominated probes (growing-context).
    prefillTokensPerSec: number;
    // DECODE speed (the OUTPUT metric): completionTokens / (totalTime −
    // ttft) — sustained generation speed over the OUTPUT phase only; 0 when
    // the generation phase has no duration
    tokensPerSec: number;
    // Present when the run failed; carries the error message
    error?: string;
};

// User-facing benchmark configuration.
export type BenchConfig = {
    // The exact prompt sent to the model on every iteration
    prompt: string;
    // Number of iterations to run against the model
    iterations: number;
    // How many iterations may be in flight at once (default 1 = sequential)
    concurrency: number;
    // Cancellation signal (NOT part of the measurement config): once aborted,
    // runs still queued are recorded as cancelled without contacting the
    // provider, in-flight streaming requests reject via the transport, and
    // the bench settles immediately with the cancelled runs on record.
    signal?: AbortSignal;
};

// LIVE STREAMING PROGRESS: one tick per streamed chunk, fired by the engine
// (BenchHooks.onStream) so a UI can show in-flight readouts ("1,203 tok
// received") WHILE a run is still generating — before the run settles into
// its final BenchRun. High frequency: throttle before rendering.
export type BenchStreamTick = {
    // 0-based iteration index this chunk belongs to
    index: number;
    // Characters received so far in THIS run (accumulated across chunks)
    chars: number;
    // Estimated tokens received so far (~chars/4 — the engine's estimation
    // heuristic; provider usage only finalizes the counts at settle time)
    tokens: number;
    // Seconds since THIS run started
    elapsed: number;
    // Live sustained rate over the generation phase (elapsed - ttft), in
    // tokens/second; 0 before the first token lands (no phase to measure)
    tokensPerSec: number;
    // true on the run's FIRST chunk — lets a UI flush throttled updates
    // immediately so the in-flight row appears without delay
    first: boolean;
};

// Optional hooks injected into runBench for observability and testability.
export type BenchHooks = {
    // Monotonic ms clock. Defaults to performance.now()/Date.now(). Injecting a
    // fake clock makes every timing fully deterministic (used by tests).
    clock?: () => number;
    // ISO timestamp source for report.createdAt. Defaults to new Date().toISOString().
    now?: () => string;
    // Fired immediately after each run finishes (success or failure)
    onRun?: (run: BenchRun) => void;
    // Fired on EVERY streamed chunk of every run (live in-flight feedback —
    // see BenchStreamTick). Much higher frequency than onRun: throttle
    // before writing to a store or rendering.
    onStream?: (tick: BenchStreamTick) => void;
    // Free-form progress logger, e.g. "run 3/6 finished in 4.21s"
    onLog?: (message: string) => void;
};

// Aggregated statistics for one model's benchmark.
// Empty-input safe: every field is 0 (or 0.0) when there are no runs, so the
// dashboard can render reports that had total failures without NaN.
export type BenchSummary = {
    // Model identifier (matches BenchProvider.model / BenchmarkReport.model)
    model: string;
    // Total attempts (successful + failed)
    runCount: number;
    // Attempts that completed without error
    completedRuns: number;
    // Attempts that errored
    failedRuns: number;
    // completedRuns / runCount, in [0, 1] (0 for no runs)
    successRate: number;
    // Fastest first-token latency across successful runs, seconds
    minTtft: number;
    // Slowest first-token latency across successful runs, seconds
    maxTtft: number;
    // Arithmetic mean of TTFT across successful runs, seconds
    avgTtft: number;
    // Median TTFT across successful runs, seconds
    medianTtft: number;
    // Fastest full generation time, seconds
    minTime: number;
    // Slowest full generation time, seconds
    maxTime: number;
    // Arithmetic mean of full generation time, seconds
    avgTime: number;
    // Mean sustained DECODE speed (output metric) across successful runs,
    // tokens/second
    throughput: number;
    // Mean PREFILL speed (input metric) across successful runs:
    // mean of per-run promptTokens / ttft, tokens/second
    avgPrefillTokensPerSec: number;
    // Best single-run sustained decode speed, tokens/second
    maxTokensPerSec: number;
    // Mean completion tokens across successful runs
    avgCompletionTokens: number;
    // Mean prompt tokens across successful runs
    avgPromptTokens: number;
    // Total wall time for the whole benchmark, seconds
    wallTime: number;
};

// The final artifact of one model benchmark: config, raw runs, and summary.
// The dashboard renders a list of these (one per model) side by side.
export type BenchmarkReport = {
    // Model identifier (BenchProvider.model)
    model: string;
    // The configuration that produced the runs
    config: {
        prompt: string;
        iterations: number;
        concurrency: number;
    };
    // ISO timestamp of report creation
    createdAt: string;
    // Total wall time for the whole benchmark, seconds
    wallTime: number;
    // Raw per-iteration measurements (ordered by run.index)
    runs: BenchRun[];
    // Aggregated statistics derived from `runs` (see summarizeRuns)
    summary: BenchSummary;
};